#!/usr/bin/env python3
"""Task symmetry group for the two-segment quartet instrument (D02 shared lib).

Four points with fixed roles A/B/C/D form two segments AB and CD.
Legal group G8 is generated by A<->B, C<->D and whole-segment AB<->CD:
8 elements. It is NOT the full S4 (which would discard pairing info).

Convention: a configuration is an [..., 4, 2] array in role order
(A, B, C, D), or a flat [..., 8] vector with the same ordering.
The SAME group element must be applied to every state and edit of one
quartet (transform base coordinates, re-apply the identically permuted
edit); permuting only the AB endpoint state alone is a different object.
"""
from __future__ import annotations
import itertools
import numpy as np

_S1 = (1, 0, 2, 3)  # A <-> B
_S2 = (0, 1, 3, 2)  # C <-> D
_S3 = (2, 3, 0, 1)  # AB <-> CD


def _compose(p, q):
    """Apply q then p (both as index tuples)."""
    return tuple(p[q[i]] for i in range(4))


def _build_group():
    seen = {(0, 1, 2, 3)}
    frontier = [(0, 1, 2, 3)]
    gens = (_S1, _S2, _S3)
    while frontier:
        cur = frontier.pop()
        for g in gens:
            for h in (_compose(g, cur), _compose(cur, g)):
                if h not in seen:
                    seen.add(h)
                    frontier.append(h)
    return sorted(seen)


GROUP: list[tuple[int, int, int, int]] = _build_group()
IDENTITY = (0, 1, 2, 3)
assert len(GROUP) == 8, GROUP


def invert(g) -> tuple[int, int, int, int]:
    inv = [0] * 4
    for i, j in enumerate(g):
        inv[j] = i
    return tuple(inv)


def apply(x: np.ndarray, g) -> np.ndarray:
    """Permute point roles of x by g. Accepts [...,4,2] or [...,8]."""
    x = np.asarray(x, dtype=float)
    g = list(g)
    if x.shape[-2:] == (4, 2) or (x.ndim >= 2 and x.shape[-2] == 4 and x.shape[-1] == 2):
        return x[..., g, :]
    if x.shape[-1] == 8:
        y = x.reshape(x.shape[:-1] + (4, 2))[..., g, :]
        return y.reshape(x.shape)
    raise ValueError(f"expected [...,4,2] or [...,8], got {x.shape}")


def group_average_logits(logit_fn, x: np.ndarray) -> np.ndarray:
    """Mean logit over the 8 legal relabelings. Cost: 8 forward passes."""
    acc = None
    for g in GROUP:
        v = np.asarray(logit_fn(apply(x, g)), dtype=float)
        acc = v if acc is None else acc + v
    return acc / len(GROUP)
