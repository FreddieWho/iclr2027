#!/usr/bin/env python3
"""L007-C1: equivalence-representation probe (zero training).

The oracle relation is invariant under the 8-element group generated by
swapping A<->B, C<->D, and the two segments (verified: the orientation
products and the margin are unchanged). If the model's predicted root
moves under those relabelings, part of the "location error" is a
representation artifact rather than geometry.

Design (fixed before running):
  - same 200 eval_202 aimed paths, NOT re-selected per representation;
  - 8 permutations applied jointly to x and e;
  - oracle t_star must be identical across permutations (asserted, with a
    tolerance for bisection noise) -- this validates the invariance claim;
  - per path: hit set across the 8 representations, signed root spread
    among hitting representations, extra-turn counts.
  - "inequivalent" := root spread > 0.03 OR hit status not unanimous.

PRE-REGISTERED criterion: for >=2/3 models, the parent-clustered fraction
of inequivalent paths has a 95% CI lower bound > 0.10 -> support; if all
three models' CI upper bounds < 0.10 -> negate; else undetermined.

NEW outputs only: artifacts/next_novelty/l007_perm/
"""
import argparse
import importlib.util
import json
import sys
from pathlib import Path

import numpy as np
import torch

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "experiments" / "last15h" / "shared"))
sys.path.insert(0, str(ROOT / "experiments" / "discovery_campaign"))
sys.path.insert(0, str(ROOT / "experiments" / "last15h"))
torch.set_num_threads(4)
from paths import locate_model_turns, locate_oracle_turns, scan_linear  # noqa: E402
from common import load_model, preprocess  # noqa: E402

ART = ROOT / "artifacts" / "discovery_campaign"
OUT = ROOT / "artifacts" / "next_novelty" / "l007_perm"
SEEDS = [11, 23, 47]
# 8 permutations: (swap AB, swap CD, swap segments)
PERMS = [(sab, scd, sseg) for sab in (0, 1) for scd in (0, 1)
         for sseg in (0, 1)]


def apply_perm(x, e, p):
    sab, scd, sseg = p
    idx = [0, 1, 2, 3]
    if sab:
        idx[0], idx[1] = idx[1], idx[0]
    if scd:
        idx[2], idx[3] = idx[3], idx[2]
    if sseg:
        idx[0], idx[2] = idx[2], idx[0]
        idx[1], idx[3] = idx[3], idx[1]
    idx = np.array(idx)
    return np.asarray(x)[idx], np.asarray(e)[idx]


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--n_eval_paths", type=int, default=200)
    p.add_argument("--seed_eval", type=int, default=202)
    p.add_argument("--n_scan", type=int, default=33)
    p.add_argument("--out", type=Path, default=OUT)
    a = p.parse_args()
    spec = importlib.util.spec_from_file_location(
        "n01b", str(ROOT / "experiments" / "last15h" / "n01_brackets.py"))
    n01b = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(n01b)
    de = np.load(ART / "scenes" / "eval_202" / "scenes.npz")
    Xe = de["positions"].astype(float)
    ev_paths = n01b.aimed_single_turns(
        Xe, np.random.default_rng(a.seed_eval), a.n_eval_paths,
        seed=a.seed_eval)

    out = {"n_paths": len(ev_paths), "n_perms": len(PERMS),
           "criterion": ("inequivalent := root spread > 0.03 OR hit status "
                         "not unanimous; support if >=2/3 models have "
                         "parent-clustered CI lower bound > 0.10"),
           "oracle_invariance": {}, "models": {}}
    rng = np.random.default_rng(31337)

    for seed in SEEDS:
        model, stats = load_model(ART / ("r04b_s%d" % seed) / "flipmine")
        model.eval()

        def predict(xs):
            with torch.no_grad():
                lg = model(preprocess(np.asarray(xs, np.float32),
                                      stats)).numpy()
            lg = np.asarray(lg, float).reshape(-1)
            return lg, (lg > 0).astype(int)

        rows = []
        tstar_spread = []
        for ep in ev_paths:
            x0 = Xe[ep["parent_id"]]
            e0 = np.asarray(ep["edit"], float)
            rec = {"parent": int(ep["parent_id"]), "hits": [],
                   "roots": [], "extra": [], "tstars": []}
            for p_ in PERMS:
                x, e = apply_perm(x0, e0, p_)
                sc = scan_linear(x, e, predict, n_scan=a.n_scan)
                ot = locate_oracle_turns(x, e, sc)
                if len(ot) != 1:
                    rec["hits"].append(0)
                    continue
                rec["tstars"].append(ot[0]["t_star"])
                mt = locate_model_turns(x, e, sc, predict)
                same = [m for m in mt if m["old"] == 0 and m["new"] == 1]
                rec["extra"].append(len(mt) - 1 if mt else 0)
                if not same:
                    rec["hits"].append(0)
                else:
                    best = min(same, key=lambda m: abs(m["t_theta"] - ot[0]["t_star"]))
                    rec["hits"].append(1)
                    rec["roots"].append(best["t_theta"])
            if len(rec["tstars"]) >= 2:
                tstar_spread.append(float(np.max(rec["tstars"]) -
                                          np.min(rec["tstars"])))
            hits = rec["hits"]
            spread = (float(np.max(rec["roots"]) - np.min(rec["roots"]))
                      if len(rec["roots"]) >= 2 else 0.0)
            rec["root_spread"] = spread
            rec["unanimous"] = bool(len(set(hits)) == 1)
            rec["inequivalent"] = bool(spread > 0.03 or not rec["unanimous"])
            rows.append(rec)

        # parent-clustered bootstrap of the inequivalent fraction
        par = np.array([r["parent"] for r in rows])
        flag = np.array([1.0 if r["inequivalent"] else 0.0 for r in rows])
        ups = np.unique(par)
        groups = [np.nonzero(par == u)[0] for u in ups]
        boots = []
        for _ in range(2000):
            draw = rng.choice(len(groups), size=len(groups), replace=True)
            idx = np.concatenate([groups[i] for i in draw])
            boots.append(flag[idx].mean())
        lo, hi = np.quantile(boots, [0.025, 0.975])
        # path-level bootstrap (reviewer's point: n_paths overstates n_parents)
        boots_p = [flag[rng.choice(len(flag), len(flag), replace=True)].mean()
                   for _ in range(2000)]
        lo_p, hi_p = np.quantile(boots_p, [0.025, 0.975])
        out["models"]["s%d" % seed] = {
            "inequiv_frac": round(float(flag.mean()), 4),
            "ci_parent_cluster": [round(float(lo), 4), round(float(hi), 4)],
            "ci_path_level": [round(float(lo_p), 4), round(float(hi_p), 4)],
            "n_parents": int(len(ups)),
            "root_spread_median": round(float(np.median(
                [r["root_spread"] for r in rows])), 4),
            "mixed_hit_frac": round(float(np.mean(
                [0.0 if r["unanimous"] else 1.0 for r in rows])), 4),
            "tstar_spread_max": round(float(np.max(tstar_spread))
                                      if tstar_spread else 0.0, 6),
        }
        print("s%d" % seed, out["models"]["s%d" % seed], flush=True)
        out["oracle_invariance"]["s%d" % seed] = round(
            float(np.max(tstar_spread)) if tstar_spread else 0.0, 6)

    los = [out["models"]["s%d" % s]["ci_parent_cluster"][0] for s in SEEDS]
    his = [out["models"]["s%d" % s]["ci_parent_cluster"][1] for s in SEEDS]
    n_support = sum(1 for v in los if v > 0.10)
    out["criterion_met"] = n_support >= 2
    if n_support >= 2:
        out["verdict"] = "representation-sensitivity supported"
    elif all(v < 0.10 for v in his):
        out["verdict"] = "negated (all models below 10%)"
    else:
        out["verdict"] = "undetermined"
    a.out.mkdir(parents=True, exist_ok=True)
    json.dump(out, open(a.out / "L007_PERM.json", "w"), indent=1, default=float)
    print("criterion_met:", out["criterion_met"], "verdict:", out["verdict"])
    print("DONE ->", a.out)


if __name__ == "__main__":
    main()
